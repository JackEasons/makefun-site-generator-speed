/** The characters a backslash escapes: \ ` * _ [ ] ( ) # + - . ! > */
function isEscapable(c) {
  return c === 92 || c === 96 || c === 42 || c === 95 || c === 91 || c === 93 || c === 40 || c === 41 ||
    c === 35 || c === 43 || c === 45 || c === 46 || c === 33 || c === 62;
}

/** The first index from `from` where `s` holds `what` outside a backslash escape, or -1. */
function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s.charCodeAt(j) === 92 && j + 1 < s.length && isEscapable(s.charCodeAt(j + 1))) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * from `from` (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s.charCodeAt(j);
    if (c === 92 && j + 1 < s.length && isEscapable(s.charCodeAt(j + 1))) {
      j++;
      continue;
    }
    if (c !== 42) continue;
    if (s.charCodeAt(j + 1) === 42) {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

const INLINE_RE = /[\\`*[&<>"']/g;

/** `s` rendered inline; `link(target)` is a link's href. A regex finds each special character;
 * plain runs between them are escaped whole, so ordinary text costs one scan, not one per char. */
function inline(s, link) {
  let out = '';
  let i = 0;
  let plain = 0; // start of the current run of plain text
  INLINE_RE.lastIndex = 0;
  let m;
  while ((m = INLINE_RE.exec(s)) !== null) {
    const at = m.index;
    const c = m[0];
    if (c === '\\') {
      if (at + 1 < s.length && isEscapable(s.charCodeAt(at + 1))) {
        if (at > plain) out += escapeHtml(s.slice(plain, at));
        out += ESCAPES[s[at + 1]] ?? s[at + 1];
        INLINE_RE.lastIndex = at + 2;
        i = at + 2;
        plain = i;
        continue;
      }
      continue; // a backslash before anything else is itself; the run covers it
    }
    if (c === '`') {
      const j = s.indexOf('`', at + 1);
      if (j > at + 1) {
        if (at > plain) out += escapeHtml(s.slice(plain, at));
        out += `<code>${escapeHtml(s.slice(at + 1, j))}</code>`;
        INLINE_RE.lastIndex = j + 1;
        i = j + 1;
        plain = i;
      }
      continue;
    }
    if (c === '*') {
      if (s.charCodeAt(at + 1) === 42) {
        const j = findUnescaped(s, '**', at + 2);
        if (j > at + 2) {
          if (at > plain) out += escapeHtml(s.slice(plain, at));
          out += `<strong>${inline(s.slice(at + 2, j), link)}</strong>`;
          INLINE_RE.lastIndex = j + 2;
          i = j + 2;
          plain = i;
        } else {
          // no closer: both stars are literal, as the reference leaves them
          INLINE_RE.lastIndex = at + 2;
        }
        continue;
      }
      const j = findSingleStar(s, at + 1);
      if (j > at + 1) {
        if (at > plain) out += escapeHtml(s.slice(plain, at));
        out += `<em>${inline(s.slice(at + 1, j), link)}</em>`;
        INLINE_RE.lastIndex = j + 1;
        i = j + 1;
        plain = i;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', at + 1);
      const mm = k !== -1 && s.charCodeAt(k + 1) === 40 ? s.indexOf(')', k + 2) : -1;
      const target = mm === -1 ? '' : s.slice(k + 2, mm);
      if (target !== '' && !/\s/.test(target)) {
        if (at > plain) out += escapeHtml(s.slice(plain, at));
        out += `<a href="${escapeHtml(link(target))}">${inline(s.slice(at + 1, k), link)}</a>`;
        INLINE_RE.lastIndex = mm + 1;
        i = mm + 1;
        plain = i;
      }
      continue;
    }
    // & < > " ' : escaped where they fall; the run is flushed up to them.
    if (at > plain) out += escapeHtml(s.slice(plain, at));
    out += ESCAPES[c];
    i = at + 1;
    plain = i;
  }
  if (plain < s.length) out += escapeHtml(s.slice(plain));
  return out;
}

/** A line trimmed of spaces and tabs at both ends. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

/** A fence-open line's language, or null when the line is no fence. */
function fenceLang(line) {
  if (!line.startsWith('```')) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

/** Whether `line` closes a fence. */
function isFenceClose(line) {
  if (!line.startsWith('```')) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's { depth, text }, or null (a heading's text is never empty). */
function headingOf(line) {
  let d = 0;
  while (d < line.length && line.charCodeAt(d) === 35) d++;
  if (d === 0 || d > 6) return null;
  if (d >= line.length) return null;
  const c = line.charCodeAt(d);
  if (c !== 32 && c !== 9) return null;
  const text = trimLine(line.slice(d));
  if (text === '') return null;
  return { depth: d, text };
}

/** Whether `line` is a thematic break. */
function isHr(line) {
  if (!line.startsWith('---') && !line.startsWith('***')) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: a blank line, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  return isBlank(line) || fenceLang(line) !== null || headingOf(line) !== null || isHr(line);
}

/**
 * `src` rendered: its HTML (each block on its own lines, a "\n" after the last), its table of
 * contents (every level 2 and 3 heading: level, id and its inline HTML) and its excerpt (the first
 * paragraph's inline HTML, or ""). `src` is a string, or { lines, start } to reuse an already
 * split line array.
 */
function renderMarkdown(src, link) {
  const lines = typeof src === 'string' ? src.split('\n') : src.lines;
  const start = typeof src === 'string' ? 0 : src.start;
  const ids = new Set();
  const nextSlug = new Map();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = start;
  const end = lines.length;
  while (i < end) {
    const line = lines[i];
    if (isBlank(line)) {
      i++;
      continue;
    }
    const lang = fenceLang(line);
    if (lang !== null) {
      const body = [];
      i++;
      while (i < end && !isFenceClose(lines[i])) body.push(lines[i++]);
      i++;
      const cls = lang === '' ? '' : ` class="language-${escapeHtml(lang)}"`;
      let code = '';
      for (const l of body) {
        code += escapeHtml(l);
        code += '\n';
      }
      blocks.push(`<pre><code${cls}>${code}</code></pre>\n`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids, nextSlug);
      const html = inline(heading.text, link);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>\n`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) {
      blocks.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < end && lines[i].charCodeAt(0) === 62) {
        const l = lines[i++];
        body.push(l.charCodeAt(1) === 32 ? l.slice(2) : l.slice(1));
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>\n' : `<blockquote>\n<p>${inline(kept.join('\n'), link)}</p>\n</blockquote>\n`);
      continue;
    }
    const bullet = line.startsWith('- ') || line.startsWith('* ');
    let ordered = null;
    if (!bullet) {
      // digits and '. ' — at most 9 digits
      let d = 0;
      while (d < 9 && d < line.length) {
        const c = line.charCodeAt(d);
        if (c >= 48 && c <= 57) d++;
        else break;
      }
      if (d > 0 && d + 1 < line.length && line.charCodeAt(d) === 46 && line.charCodeAt(d + 1) === 32) ordered = d;
    }
    if (bullet || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      let start = 1;
      if (isOrdered) start = Number(line.slice(0, ordered));
      while (i < end) {
        const l = lines[i];
        let item = null;
        if (isOrdered) {
          let d = 0;
          while (d < 9 && d < l.length) {
            const c = l.charCodeAt(d);
            if (c >= 48 && c <= 57) d++;
            else break;
          }
          if (d > 0 && d + 1 < l.length && l.charCodeAt(d) === 46 && l.charCodeAt(d + 1) === 32) item = trimLine(l.slice(d + 2));
        } else if (l.startsWith('- ') || l.startsWith('* ')) {
          item = trimLine(l.slice(2));
        }
        if (item !== null) {
          items.push([item]);
          i++;
        } else if (l.charCodeAt(0) === 32 && l.charCodeAt(1) === 32) {
          // a line of two or more spaces then a non-space continues the item
          let j = 2;
          while (j < l.length && l.charCodeAt(j) === 32) j++;
          if (j < l.length && !/\s/.test(l[j])) {
            items[items.length - 1].push(trimLine(l));
            i++;
          } else break;
        } else break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      const open = isOrdered && start !== 1 ? `<ol start="${start}">` : `<${tag}>`;
      let html = `${open}\n`;
      for (const parts of items) html += `<li>${inline(parts.join('\n'), link)}</li>\n`;
      html += `</${tag}>\n`;
      blocks.push(html);
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < end && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const html = inline(body.join('\n'), link);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>\n`);
  }
  return { html: blocks.join(''), toc, excerpt: excerpt ?? '' };
}

